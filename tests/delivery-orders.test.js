const { test, after } = require('node:test');
const assert = require('node:assert/strict');
const connectionPath = require.resolve('../server/database/connection');
require.cache[connectionPath] = { id: connectionPath, filename: connectionPath, loaded: true, exports: { connectToDatabase: async () => {} } };
const whatsappPath = require.resolve('../server/utils/whatsapp');
require.cache[whatsappPath] = { id: whatsappPath, filename: whatsappPath, loaded: true, exports: { ADMIN_WHATSAPP_NUMBER: '', sendWhatsAppMessage: () => {}, getWhatsAppClickLink: () => '', formatWhatsAppNumber: value => value } };
const Order = require('../server/models/order');
const TableConfig = require('../server/models/tableConfig');
const Settings = require('../server/models/settings');
const User = require('../server/models/registerUsers');
const records = [];
Order.prototype.save = async function () {
    await this.validate();
    this.createdAt = new Date();
    records.push(this.toObject());
    return this;
};
const matches = (order, filter) => Object.entries(filter).every(([key, value]) => value?.$ne ? order[key] !== value.$ne : String(order[key]) === String(value));
Order.find = (filter = {}) => ({ sort() { return this; }, lean: async () => records.filter(order => matches(order, filter)) });
Order.findOneAndUpdate = async (filter, update) => {
    const order = records.find(order => matches(order, filter));
    if (!order) return null;
    Object.assign(order, update.$set);
    return order;
};
TableConfig.find = () => ({ sort: () => ({ lean: async () => [{ number: 3, zone: 'Main room', seats: 4, shape: 'square' }] }) });
Settings.findOne = () => ({ lean: async () => ({ restaurantName: 'Le Patio', currency: 'TND' }) });
User.countDocuments = async () => 1;
User.findOne = async () => ({ _id: 'admin-test', email: 'test@example.com', password: 'test-only' });
const app = require('../server/Server');
const listening = new Promise(resolve => app.server.listen(0, '127.0.0.1', resolve));
after(async () => { await new Promise(resolve => app.server.close(resolve)); });

test('delivery requires contact and address, stays separate from tables, and each delivery closes independently', async () => {
    await listening;
    const base = `http://127.0.0.1:${app.server.address().port}`;
    const payload = { name: 'Client test', PhoneNumber: '20000000', serviceType: 'delivery', deliveryAddress: '12 rue du Test, Houmt Souk', TableNumber: 3, items: [{ itemName: 'Chicken burger', itemPrice: 10.5, itemQty: 1 }], totalPrice: 10.5 };
    const post = body => fetch(`${base}/Order_Details`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
    assert.equal((await post({ ...payload, deliveryAddress: '' })).status, 400);
    assert.equal((await post({ ...payload, PhoneNumber: '' })).status, 400);
    assert.equal((await post({ ...payload, name: '' })).status, 400);
    assert.equal((await post({ ...payload, deliveryAddress: 'x'.repeat(501) })).status, 400);
    assert.equal((await post({ ...payload, items: [] })).status, 400);
    assert.equal(records.length, 0);
    const first = await post(payload);
    assert.equal(first.status, 201);
    const firstId = (await first.json()).orderId;
    const second = await post({ ...payload, name: 'Autre client', deliveryAddress: '20 avenue du Test, Djerba' });
    const secondId = (await second.json()).orderId;
    assert.notEqual(firstId, secondId);
    assert.equal(records[0].TableNumber, undefined);
    assert.equal(records[0].deliveryAddress, payload.deliveryAddress);
    assert.equal(records[0].seatCount, 1);
    assert.equal((await fetch(`${base}/api/delivery-orders`)).status, 401);
    assert.equal((await fetch(`${base}/api/orders/${firstId}/delivered`, { method: 'PATCH' })).status, 401);
    const login = await fetch(`${base}/login`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email: 'test@example.com', password: 'test-only' }), redirect: 'manual' });
    const cookie = login.headers.get('set-cookie').split(';')[0];
    const headers = { Cookie: cookie };
    const list = await (await fetch(`${base}/api/delivery-orders`, { headers })).json();
    assert.deepEqual(list.orders.map(order => order.id), [firstId, secondId]);
    const tablePage = await (await fetch(`${base}/ImgUploader_add`, { headers })).text();
    assert.ok(tablePage.includes(`data-delivery-id="${firstId}"`));
    assert.ok(tablePage.includes(`data-delivery-id="${secondId}"`));
    assert.ok(tablePage.includes('12 rue du Test, Houmt Souk'));
    assert.ok(tablePage.includes('class="table-card free" data-table-number="3"'));
    assert.ok(tablePage.includes('delivery-scooter.svg'));
    const publicTablePage = await (await fetch(`${base}/ImgUploader_add`)).text();
    assert.ok(!publicTablePage.includes(payload.deliveryAddress));
    const checkout = await (await fetch(`${base}/Order_Details?mode=delivery`)).text();
    assert.ok(checkout.includes('id="deliveryService"'));
    assert.ok(checkout.includes('id="deliveryAddress"'));
    const { Script } = require('node:vm');
    for (const script of checkout.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)) new Script(script[1]);
    const ordersPage = await (await fetch(`${base}/Orders`, { headers })).text();
    assert.ok(ordersPage.includes('Livraison à domicile'));
    assert.ok(ordersPage.includes(payload.deliveryAddress));
    for (const script of ordersPage.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)) new Script(script[1]);
    assert.equal((await post({ ...payload, serviceType: 'dine-in', TableNumber: '', seatCount: 1 })).status, 400);
    assert.equal((await post({ ...payload, serviceType: 'dine-in', TableNumber: 3, seatCount: 2 })).status, 201);
    const tableOrder = records[2];
    assert.equal(tableOrder.deliveryAddress, undefined);
    assert.equal((await fetch(`${base}/api/orders/${tableOrder._id}/delivered`, { method: 'PATCH', headers })).status, 404);
    assert.equal((await fetch(`${base}/api/orders/${firstId}/delivered`, { method: 'PATCH', headers })).status, 200);
    assert.equal(records[0].status, 'closed');
    assert.ok(records[0].deliveredAt instanceof Date);
    assert.equal(records[1].status, 'active');
    assert.equal(records[2].status, 'active');
    const remaining = await (await fetch(`${base}/api/delivery-orders`, { headers })).json();
    assert.deepEqual(remaining.orders.map(order => order.id), [secondId]);
});
