process.env.NODE_ENV = 'test';
const { test, after } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const connectionPath = require.resolve('../server/database/connection');
require.cache[connectionPath] = { id: connectionPath, filename: connectionPath, loaded: true, exports: { connectToDatabase: async () => {} } };
const Settings = require('../server/models/settings');
const User = require('../server/models/registerUsers');
const { imageContentType } = require('../server/utils/websiteLogo');
const smallPng = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+a3ioAAAAASUVORK5CYII=', 'base64');
let settings = { restaurantName: 'Le Patio', address: 'Djerba', currency: 'TND' };
let writes = 0;
Settings.findOne = () => ({ lean: async () => settings });
Settings.findOneAndUpdate = async (filter, update) => { writes++; Object.assign(settings, update.$set); return settings; };
User.countDocuments = async () => 1;
User.findOne = () => {
    const admin = { _id: 'test-admin', email: 'test@example.com', password: 'test-only' };
    return { then: (resolve, reject) => Promise.resolve(admin).then(resolve, reject), lean: async () => admin };
};
const app = require('../server/Server');
const listening = new Promise(resolve => app.server.listen(0, '127.0.0.1', resolve));
after(async () => { await new Promise(resolve => app.server.close(resolve)); });

test('logo defaults to the supplied asset and an authenticated replacement is publicly served with cache revalidation', async () => {
    await listening;
    const base = `http://127.0.0.1:${app.server.address().port}`;
    const defaultLogo = await fetch(`${base}/images/logo.png`);
    assert.equal(defaultLogo.status, 200);
    assert.deepEqual(Buffer.from(await defaultLogo.arrayBuffer()), fs.readFileSync(path.join(__dirname, '../server/public/images/logo.png')));
    const upload = (blob, cookie, name = 'logo.png') => {
        const form = new FormData();
        if (blob) form.append('logo', blob, name);
        return fetch(`${base}/api/settings/logo`, { method: 'POST', headers: cookie ? { Cookie: cookie } : {}, body: form });
    };
    assert.equal((await upload(new Blob([smallPng], { type: 'image/png' }))).status, 401);
    assert.equal(writes, 0);
    const login = await fetch(`${base}/login`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email: 'test@example.com', password: 'test-only' }), redirect: 'manual' });
    const cookie = login.headers.get('set-cookie').split(';')[0];
    const settingsPage = await (await fetch(`${base}/Settings`, { headers: { Cookie: cookie } })).text();
    assert.ok(settingsPage.includes('id="websiteLogoForm"'));
    assert.ok(settingsPage.includes('id="websiteLogoPreview"'));
    assert.equal((await upload(null, cookie)).status, 400);
    assert.equal((await upload(new Blob(['fake image'], { type: 'image/png' }), cookie)).status, 400);
    assert.equal((await upload(new Blob(['<svg/>'], { type: 'image/svg+xml' }), cookie, 'logo.svg')).status, 400);
    assert.equal((await upload(new Blob([Buffer.alloc(5 * 1024 * 1024 + 1)], { type: 'image/png' }), cookie)).status, 413);
    assert.equal(writes, 0);
    const saved = await upload(new Blob([smallPng], { type: 'image/png' }), cookie);
    assert.equal(saved.status, 200);
    assert.match((await saved.json()).logoUrl, /^\/images\/logo\.png\?v=/);
    assert.equal(settings.restaurantName, 'Le Patio');
    assert.equal(settings.address, 'Djerba');
    assert.equal(settings.currency, 'TND');
    assert.deepEqual(settings.logo.data, smallPng);
    const served = await fetch(`${base}/images/logo.png`);
    assert.equal(served.headers.get('content-type'), 'image/png');
    assert.equal(served.headers.get('cache-control'), 'public, no-cache');
    assert.deepEqual(Buffer.from(await served.arrayBuffer()), smallPng);
    const previousTag = served.headers.get('etag');
    assert.equal((await fetch(`${base}/images/logo.png`, { cache: 'force-cache', headers: { 'If-None-Match': previousTag } })).status, 304);
    const replacement = fs.readFileSync(path.join(__dirname, '../server/public/images/logo.png'));
    assert.equal((await upload(new Blob([replacement], { type: 'image/png' }), cookie)).status, 200);
    assert.notEqual((await fetch(`${base}/images/logo.png`)).headers.get('etag'), previousTag);
    assert.equal(imageContentType(Buffer.from('<html>')), null);
});
